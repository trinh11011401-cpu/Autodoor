#ifndef APP_PROTOCOL_H
#define APP_PROTOCOL_H

#include <stdint.h>

enum { CAN_ID_COMMAND = 0x100U, CAN_ID_STATUS = 0x101U,
       CAN_ID_HEARTBEAT = 0x102U, CAN_ID_ENCODER = 0x103U };

typedef enum {
    CMD_STOP = 0, CMD_OPEN = 1, CMD_CLOSE = 2, CMD_LOCK = 3,
    CMD_UNLOCK = 4, CMD_CLEAR_FAULT = 5, CMD_JOG_OPEN = 6, CMD_JOG_CLOSE = 7
} Command;

typedef enum {
    DOOR_UNKNOWN = 0, DOOR_CLOSED = 1, DOOR_OPENING = 2,
    DOOR_OPENED = 3, DOOR_CLOSING = 4, DOOR_STOPPED = 5
} DoorState;

enum {
    FAULT_OBSTACLE = 0x01U, FAULT_CAN_LOST = 0x02U,
    FAULT_BUS_OFF = 0x04U, FAULT_ENCODER = 0x08U,
    FAULT_TRAVEL = 0x10U, FAULT_LIMIT = 0x20U,
    FAULT_UNHOMED = 0x40U, FAULT_POWER_UP = 0x80U
};

#define FAULT_BLOCKING (FAULT_CAN_LOST | FAULT_BUS_OFF | FAULT_ENCODER | \
                        FAULT_TRAVEL | FAULT_LIMIT)

enum {
    STATUS_CLOSED = 0x01U, STATUS_HOMED = 0x02U,
    STATUS_REVERSING = 0x04U, STATUS_LINK_OK = 0x08U,
    STATUS_BENCH = 0x10U, STATUS_ENCODER_OK = 0x20U,
    STATUS_TARGET_ESTIMATED = 0x40U
};

typedef struct {
    uint16_t id;
    uint8_t dlc;
    uint8_t data[8];
} CanFrame;

#endif
